function quizChallenge(
  title: string,
  description: string,
  assignedTo: string[],
  difficulty: Challenge['difficulty'],
  category: 'math' | 'english',
  quiz: QuizQuestion[],
): Challenge {
  return {
    id: makeId(),
    title,
    description,
    category,
    kind: 'quiz',
    difficulty,
    requiresApproval: false,
    recurrence: 'daily',
    assignedTo,
    createdBy: 'system',
    quiz,
    active: true,
    createdAt: new Date().toISOString(),
  };
}

